// Writes public/crest-geometry.js: each crest shape's bounding box, and its rivets spaced
// along the line STUD units inside the outline, with one at each corner. Run it after
// changing a shape: node scripts/crest-geometry.mjs
/* global document -- the measuring runs in the browser page */
import { chromium } from 'playwright';
import { writeFileSync } from 'node:fs';
import { SHAPES } from '../public/crest.js';

const browser = await chromium.launch();
const page = await browser.newPage();
const out = await page.evaluate(shapes => {
  const STUD = 2.6, SPACING = 12, WINDOW = 1.2, CORNER = 40 * Math.PI / 180;
  const ns = 'http://www.w3.org/2000/svg';
  const svg = document.createElementNS(ns, 'svg');
  document.body.appendChild(svg);
  const result = {};
  for (const [key, shape] of Object.entries(shapes)) {
    const path = document.createElementNS(ns, 'path');
    path.setAttribute('d', shape.d);
    svg.appendChild(path);
    const b = path.getBBox();
    const total = path.getTotalLength();
    const n = Math.ceil(total / .05);
    const pts = [];
    for (let i = 0; i < n; i++) { const p = path.getPointAtLength(i * total / n); pts.push([p.x, p.y]); }
    let area = 0;
    pts.forEach(([x, y], i) => { const [x2, y2] = pts[(i + 1) % n]; area += x * y2 - x2 * y; });
    const sign = area > 0 ? 1 : -1; // inward normal side
    const inner = [];
    for (let i = 0; i < n; i++) {
      const [ax, ay] = pts[(i - 2 + n) % n], [bx, by] = pts[(i + 2) % n];
      let tx = bx - ax, ty = by - ay; const len = Math.hypot(tx, ty) || 1; tx /= len; ty /= len;
      const q = [pts[i][0] - sign * ty * STUD, pts[i][1] + sign * tx * STUD];
      let min = Infinity;
      for (const p of pts) { const d = Math.hypot(p[0] - q[0], p[1] - q[1]); if (d < min) min = d; }
      if (min >= STUD - .03) inner.push(q);
    }
    // Arc length along the inner curve.
    const m = inner.length, acc = [0];
    for (let i = 1; i <= m; i++) acc.push(acc[i - 1] + Math.hypot(inner[i % m][0] - inner[i - 1][0], inner[i % m][1] - inner[i - 1][1]));
    const perimeter = acc[m];
    const at = s => { // point at arc length s (wrapping)
      s = ((s % perimeter) + perimeter) % perimeter;
      let lo = 0, hi = m; while (hi - lo > 1) { const mid = (lo + hi) >> 1; if (acc[mid] <= s) lo = mid; else hi = mid; }
      const t = (s - acc[lo]) / ((acc[lo + 1] - acc[lo]) || 1), a = inner[lo], c = inner[(lo + 1) % m];
      return [a[0] + (c[0] - a[0]) * t, a[1] + (c[1] - a[1]) * t];
    };
    const turn = s => {
      const a = at(s - WINDOW), c = at(s), d = at(s + WINDOW);
      const a1 = Math.atan2(c[1] - a[1], c[0] - a[0]), a2 = Math.atan2(d[1] - c[1], d[0] - c[0]);
      let t = Math.abs(a2 - a1); if (t > Math.PI) t = 2 * Math.PI - t; return t;
    };
    const step = .05, samples = Math.ceil(perimeter / step), turns = [];
    for (let i = 0; i < samples; i++) turns.push(turn(i * step));
    let corners = [];
    for (let i = 0; i < samples; i++) {
      const t = turns[i];
      if (t < CORNER) continue;
      let peak = true;
      for (let k = -30; k <= 30 && peak; k++) if (k && turns[(i + k + samples) % samples] > t + 1e-9) peak = false;
      if (peak && !corners.some(c => Math.abs(c.s - i * step) < 3)) corners.push({ s: i * step, t });
    }
    let positions = [];
    if (corners.length < 2) {
      // No corners: start at the top point nearest the vertical axis and space evenly.
      let start = 0, best = Infinity;
      for (let i = 0; i < samples; i++) { const [x, y] = at(i * step); const score = y + Math.abs(x - 24) * 3; if (score < best) { best = score; start = i * step; } }
      const k = Math.max(4, Math.round(perimeter / SPACING / 2) * 2);
      for (let i = 0; i < k; i++) positions.push(start + i * perimeter / k);
    } else {
      corners.sort((a, b) => a.s - b.s);
      corners.forEach((c, i) => {
        const next = i + 1 < corners.length ? corners[i + 1].s : corners[0].s + perimeter;
        const span = next - c.s, k = Math.max(1, Math.round(span / SPACING));
        for (let j = 0; j < k; j++) positions.push(c.s + j * span / k);
      });
    }
    const r = v => Math.round(v * 10) / 10;
    result[key] = { box: [r(b.x), r(b.y), r(b.x + b.width), r(b.y + b.height)], rivets: positions.map(at).map(([x, y]) => [r(x), r(y)]) };
    path.remove();
  }
  return result;
}, SHAPES);
await browser.close();
const rows = Object.entries(out).map(([key, { box, rivets }]) => `  ${key}: { box: ${JSON.stringify(box)}, rivets: ${JSON.stringify(rivets)} }`);
writeFileSync(new URL('../public/crest-geometry.js', import.meta.url), '// Generated by scripts/crest-geometry.mjs from the shapes in crest.js. Do not edit by hand.\n'
  + `export const SHAPE_GEOMETRY = {\n${rows.join(',\n')}\n};\n`);
